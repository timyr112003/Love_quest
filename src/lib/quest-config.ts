/**
 * Нормализует строку для проверки пароля:
 * - переводит в нижний регистр
 * - удаляет лишние пробелы
 * - удаляет пунктуацию (кроме букв и цифр)
 */
export function normalizeAnswer(input: string): string {
  return input
    .toLowerCase()
    .trim()
    .replace(/\s+/g, " ")
    .replace(/[.,!?;:«»"'\-—()]/g, "")
    .replace(/\s+/g, "");
}

/**
 * Проверяет, является ли ответ верным.
 * Сравнивает со списком допустимых вариантов.
 */
export function checkAnswer(
  input: string,
  accepted: readonly string[]
): boolean {
  const normalized = normalizeAnswer(input);
  return accepted.some((a) => normalizeAnswer(a) === normalized);
}

